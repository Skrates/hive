async function checkGeneratedOutput(path, expected) {
  let current;
  try {
    current = await readFile(path, "utf8");
  } catch {
    fail(`missing generated artifact: ${path}`);
  }
  if (current !== expected) fail("generated MCP artifacts are stale; run pnpm generate:mcp");
}

function generateStandaloneValidators(schemas) {
  const ajv = new Ajv2020({
    strict: true,
    allErrors: true,
    allowUnionTypes: true,
    code: { source: true, esm: true },
  });
  for (const schema of Object.values(schemas)) ajv.addSchema(schema);
  const validators = {
    validateMcpConformanceManifest: schemas.conformance.$id,
    validateAuthenticationHeaderManifest: schemas.authenticationHeaders.$id,
    validateHiveHandleManifest: schemas.handleKinds.$id,
    validateMcpPotentialCapabilityCatalog: schemas.potentialCapabilities.$id,
  };
  let source = standaloneCode(ajv, validators);
  source = source
    .replace(
      /const (\w+) = require\("ajv\/dist\/runtime\/equal"\)\.default;/g,
      "const $1 = generatedDeepEqual;",
    )
    .replace(
      /const (\w+) = require\("ajv\/dist\/runtime\/ucs2length"\)\.default;/g,
      "const $1 = generatedUcs2Length;",
    );
  if (source.includes("require(")) fail("standalone validator contains an unbundled runtime import");
  return `/* eslint-disable */
// @ts-nocheck
// Generated by scripts/generate-mcp-artifacts.mjs. Do not edit by hand.
function generatedDeepEqual(left, right) {
  if (left === right) return true;
  if (Array.isArray(left)) {
    return Array.isArray(right)
      && left.length === right.length
      && left.every((item, index) => generatedDeepEqual(item, right[index]));
  }
  if (left && right && typeof left === "object" && typeof right === "object") {
    const leftKeys = Object.keys(left);
    const rightKeys = Object.keys(right);
    return leftKeys.length === rightKeys.length
      && leftKeys.every((key) => Object.prototype.hasOwnProperty.call(right, key)
        && generatedDeepEqual(left[key], right[key]));
  }
  return false;
}

function generatedUcs2Length(value) {
  return [...value].length;
}

${source}
`;
}

function validateCanonicalSchemas(value) {
  const immutableIds = {
    conformance: "urn:skrates:hive:mcp:conformance-manifest:v1",
    authenticationHeaders: "urn:skrates:hive:mcp:authentication-response-headers:v1",
    handleKinds: "urn:skrates:hive:mcp:hive-handle-kinds:v1",
    potentialCapabilities: "urn:skrates:hive:mcp:potential-capabilities:v1",
  };
  const documents = {};
  for (const [name, schema] of Object.entries(value)) {
    if (schema.$schema !== "https://json-schema.org/draft/2020-12/schema") {
      fail(`${name} must use JSON Schema Draft 2020-12`);
    }
    if (schema.$id !== immutableIds[name]) fail(`${name} immutable $id drift`);
    if (!Array.isArray(schema.examples) || schema.examples.length !== 1) {
      fail(`${name} must contain exactly one canonical example`);
    }
    const ajv = new Ajv2020({ strict: true, allErrors: true, allowUnionTypes: true });
    if (!ajv.validateSchema(schema)) {
      fail(`${name} is not a valid JSON Schema: ${ajv.errorsText(ajv.errors)}`);
    }
    const validateInstance = ajv.compile(schema);
    const document = schema.examples[0];
    if (!validateInstance(document)) {
      fail(`${name} canonical example violates its schema: ${ajv.errorsText(validateInstance.errors)}`);
    }
    documents[name] = document;
  }
  return documents;
}

async function validate(schemaDocuments, value) {
  const immutableIds = {
    conformance: "urn:skrates:hive:mcp:conformance-manifest:v1",
    authenticationHeaders: "urn:skrates:hive:mcp:authentication-response-headers:v1",
    handleKinds: "urn:skrates:hive:mcp:hive-handle-kinds:v1",
    potentialCapabilities: "urn:skrates:hive:mcp:potential-capabilities:v1",
  };
  for (const [name, document] of Object.entries(value)) {
    if (document.schemaVersion !== 1) fail(`${name} must have schemaVersion 1`);
    if (schemaDocuments[name].$id !== immutableIds[name]) fail(`${name} immutable $id drift`);
  }
  const responseHeaders = value.authenticationHeaders.responseHeaders;
  if (!Array.isArray(responseHeaders) || responseHeaders.length !== 8) {
    fail("authentication response manifest must contain exactly eight entries");
  }
  const names = responseHeaders.map((entry) => entry.name);
  if (new Set(names).size !== names.length) fail("authentication response header names must be unique");
  if (names.some((name) => !/^Hive-[A-Za-z-]+$/.test(name))) fail("invalid authentication response header name");
  const secretFreeResults = value.authenticationHeaders.secretFreeResults;
  if (!Array.isArray(secretFreeResults) || secretFreeResults.length !== 1) {
    fail("authentication response manifest must contain exactly one secret-free result route");
  }
  const authenticationVariants = new Set(
    responseHeaders.flatMap((entry) => entry.resultVariants),
  );
  if (secretFreeResults.some((entry) =>
    entry.resultVariants.some((variant) => authenticationVariants.has(variant)))) {
    fail("secret-free result variants cannot overlap authentication-bearing variants");
  }
  for (const entry of secretFreeResults) {
    const canonicalVariant = entry.canonicalResult?.structuredContent?.resultVariant;
    if (entry.resultVariants.length !== 1 || entry.resultVariants[0] !== canonicalVariant) {
      fail("secret-free result route must name exactly its canonical result variant");
    }
  }
  const requestOnly = value.authenticationHeaders.requestOnlyHeaders;
  if (!Array.isArray(requestOnly) || requestOnly.length !== 1) fail("exactly one request-only header is required");
  if (names.includes(requestOnly[0].name)) fail("request-only header cannot be response-capable");

  const definitions = [...value.handleKinds.broker, ...value.handleKinds.edge];
  const kinds = definitions.map((definition) => definition.kind);
  if (new Set(kinds).size !== kinds.length) fail("Hive handle kinds must be unique");
  for (const [scope, scopedDefinitions] of [
    ["broker", value.handleKinds.broker],
    ["edge", value.handleKinds.edge],
  ]) {
    const paths = scopedDefinitions.map((definition) => definition.path);
    if (new Set(paths).size !== paths.length) fail(`Hive ${scope} handle paths must be unique`);
    for (let left = 0; left < scopedDefinitions.length; left += 1) {
      for (let right = left + 1; right < scopedDefinitions.length; right += 1) {
        if (templatesOverlap(scopedDefinitions[left].path, scopedDefinitions[right].path)) {
          fail(`ambiguous Hive ${scope} handle templates: ${scopedDefinitions[left].path} and ${scopedDefinitions[right].path}`);
        }
      }
    }
  }
  for (const definition of definitions) {
    if (!/^[A-Za-z][A-Za-z0-9]*$/.test(definition.kind)) fail(`invalid handle kind: ${definition.kind}`);
    if (definition.path.startsWith("/") || definition.path.endsWith("/")) fail(`noncanonical handle path: ${definition.path}`);
    const placeholders = definition.path.split("/").flatMap((segment) => {
      const match = /^\{([a-z][A-Za-z0-9]*)\}$/.exec(segment);
      return match ? [match[1]] : [];
    });
    if (new Set(placeholders).size !== placeholders.length) {
      fail(`duplicate handle placeholder: ${definition.path}`);
    }
    const queryNames = [...(definition.optionalQuery ?? []), ...(definition.requiredQuery ?? [])];
    if (queryNames.some((name) => placeholders.includes(name))) {
      fail(`handle coordinate appears in path and query: ${definition.path}`);
    }
    const coordinates = new Set([...placeholders, ...queryNames]);
    if ((definition.positiveIntegers ?? []).some((name) => !coordinates.has(name))) {
      fail(`positive-integer coordinate is not present in handle: ${definition.path}`);
    }
    if ((definition.optionalQuery ?? []).some((name) => definition.positiveIntegers?.includes(name))) {
      fail(`optional handle query cannot be a positive-integer coordinate: ${definition.path}`);
    }
  }

  validatePotentialCapabilityCatalog(value.potentialCapabilities, value.handleKinds, value.authenticationHeaders);

  const core = value.conformance.stableCore;
  if (core.protocolVersion !== "2026-07-28" || core.status !== "stable") fail("stable core pin drift");
  const expectedCoreFixture = {
    commit: "cc4b41617ce3601b1290d67216ea0b194a3cd9ac",
    tree: "76fe303cf95eb4cbdf7f78b750ffa4a4b3eb51cc",
    gitBlob: "eeeae659cd3eaae264d88bee1134eaad50656e1b",
  };
  for (const [field, expected] of Object.entries(expectedCoreFixture)) {
    if (core.fixtures?.[field] !== expected) fail(`stable core fixture ${field} drift`);
  }
  const fixtureManifest = JSON.parse(
    (await verifyVendoredArtifact("stable core fixtures", core.fixtures)).toString("utf8"),
  );
  if (
    fixtureManifest.revision !== core.protocolVersion
    || fixtureManifest.directoryCount !== 87
    || fixtureManifest.fileCount !== 128
  ) fail("stable core fixture manifest contents drift");
  await verifyFixtureCorpus(core.fixtures.corpus, fixtureManifest);
  const expectedSchemaTwin = {
    commit: "cc4b41617ce3601b1290d67216ea0b194a3cd9ac",
    path: "packages/core-internal/test/corpus/schema-twins/2026-07-28.schema.json",
    gitBlob: "cc44564e33305dbc07e820cdd0a97648f3852019",
  };
  for (const [field, expected] of Object.entries(expectedSchemaTwin)) {
    if (core.schemaTwin?.[field] !== expected) fail(`stable core schema twin ${field} drift`);
  }
  const twinSchemaBytes = await verifyVendoredArtifact("stable core schema twin", core.schemaTwin);
  const twinManifest = JSON.parse(
    (await verifyVendoredArtifact("stable core schema twin manifest", core.schemaTwin.manifest))
      .toString("utf8"),
  );
  const expectedTwinManifest = {
    path: "packages/core-internal/test/corpus/schema-twins/manifest.json",
    gitBlob: "904708329489222bc7cb164f2214fb98673e47c0",
    sha256: "b46ce1a533d64b5543da5ef2b071e5aa6b34417519c0cdc6ae03856364ae0d66",
    vendoredPath: "schemas/upstream/core-schema-twins-manifest.json",
  };
  for (const [field, expected] of Object.entries(expectedTwinManifest)) {
    if (core.schemaTwin.manifest?.[field] !== expected) {
      fail(`stable core schema twin manifest ${field} drift`);
    }
  }
  const twinManifestEntry = twinManifest.files?.[core.protocolVersion];
  if (
    twinManifest.source?.repository !== core.fixtures.corpus.repository
    || twinManifest.source?.commit !== core.fixtures.corpus.commit
    || twinManifestEntry?.sha256 !== core.schemaTwin.sha256
    || twinManifestEntry?.bytes !== core.schemaTwin.size
    || twinManifestEntry?.upstreamPath !== "schema/draft/schema.json"
  ) fail("stable core schema twin manifest drift");
  const twinSchema = JSON.parse(twinSchemaBytes.toString("utf8"));
  if (
    twinSchema.$schema !== "https://json-schema.org/draft/2020-12/schema"
    || typeof twinSchema.$defs !== "object"
  ) fail("stable core schema twin contents drift");

  const packageJson = JSON.parse(await readFile(resolve(root, "package.json"), "utf8"));
  const expectedPackages = {
    ...core.packages,
    [value.conformance.legacyQuarantine.package]: value.conformance.legacyQuarantine.version,
  };
  const allowedMcpPackages = new Set(
    Object.keys(expectedPackages).filter((name) => name.startsWith("@modelcontextprotocol/")),
  );
  for (const name of Object.keys(packageJson.dependencies ?? {})) {
    if (name.startsWith("@modelcontextprotocol/") && !allowedMcpPackages.has(name)) {
      fail(`unexpected direct MCP dependency: ${name}`);
    }
  }
  for (const section of ["devDependencies", "optionalDependencies", "peerDependencies"]) {
    for (const name of Object.keys(packageJson[section] ?? {})) {
      if (name.startsWith("@modelcontextprotocol/")) {
        fail(`MCP packages may not appear in ${section}: ${name}`);
      }
    }
  }
  const lockText = await readFile(resolve(root, "pnpm-lock.yaml"), "utf8");
  const importerEnd = lockText.indexOf("\npackages:");
  const importer = importerEnd === -1 ? "" : lockText.slice(0, importerEnd);
  for (const [name, expectedVersion] of Object.entries(expectedPackages)) {
    if (packageJson.dependencies?.[name] !== expectedVersion) {
      fail(`${name} package.json pin drift`);
    }
    const quotedName = name.startsWith("@") ? `'${name}'` : name;
    const escapedName = escapeRegex(quotedName);
    const escapedVersion = escapeRegex(expectedVersion);
    const lockPin = new RegExp(
      `^      ${escapedName}:\\n        specifier: ${escapedVersion}\\n        version: ${escapedVersion}(?:\\([^\\n]*\\))?$`,
      "m",
    );
    if (!lockPin.test(importer)) fail(`${name} lockfile importer pin drift`);
  }
  for (const [name, expectedVersion] of Object.entries(core.fixtureValidatorPackages)) {
    if (packageJson.devDependencies?.[name] !== expectedVersion) {
      fail(`${name} conformance validator pin drift`);
    }
    const lockPin = new RegExp(
      `^      ${escapeRegex(name)}:\\n        specifier: ${escapeRegex(expectedVersion)}\\n        version: ${escapeRegex(expectedVersion)}(?:\\([^\\n]*\\))?$`,
      "m",
    );
    if (!lockPin.test(importer)) fail(`${name} lockfile importer pin drift`);
  }

  const tasks = value.conformance.tasksExtension;
  if (!/^[0-9a-f]{40}$/.test(tasks.commit) || tasks.status !== "experimental-unofficial") {
    fail("Tasks provenance must be an exact unofficial commit pin");
  }
  if (tasks.commit !== "2c1425d9a288b9b1f489430fe1e00bb392b47e48") {
    fail("Tasks commit pin drift");
  }
  const expectedTasksArtifacts = {
    schema: {
      path: "schema/draft/schema.json",
      gitBlob: "d6ccaff7e3fb2131b5d752dd8b6f34096e58e976",
      sha256: "b17cb4a2534379c214b17770bd5d3d54f69fde16a953bfb542c58235a61274bb",
      vendoredPath: "schemas/upstream/tasks-2c1425d9.schema.json",
    },
    specification: {
      path: "specification/draft/tasks.md",
      gitBlob: "0e7fa6bfe9a998ecc257ae1df80c15b206fb518d",
      sha256: "ae908a883d8489f1ebfee47496dd8818f182b467a4196c17df98b40a3d8b2b11",
      vendoredPath: "schemas/upstream/tasks-2c1425d9.md",
    },
  };
  for (const [artifactName, expected] of Object.entries(expectedTasksArtifacts)) {
    for (const [field, expectedValue] of Object.entries(expected)) {
      if (tasks[artifactName]?.[field] !== expectedValue) {
        fail(`Tasks ${artifactName} ${field} drift`);
      }
    }
  }
  const tasksSchemaBytes = await verifyVendoredArtifact("Tasks schema", tasks.schema);
  await verifyVendoredArtifact("Tasks specification", tasks.specification);
  const tasksSchema = JSON.parse(tasksSchemaBytes.toString("utf8"));
  if (tasksSchema.$id !== "https://modelcontextprotocol.io/ext-tasks/schema.json") {
    fail("Tasks schema identity drift");
  }
}

function validatePotentialCapabilityCatalog(catalog, handles, authenticationHeaders) {
  if (
    catalog.listCache?.cacheScope !== "private"
    || catalog.listCache?.ttlMs !== 5_000
    || catalog.staticDescriptorCache?.cacheScope !== "public"
    || catalog.staticDescriptorCache?.ttlMs !== 300_000
  ) fail("potential capability catalog cache contract drift");

  const resourceKinds = catalog.resources.map((entry) => entry.handleKind);
  const referenceKinds = catalog.referenceOnlyHandles.map((entry) => entry.handleKind);
  const allKinds = [...handles.broker, ...handles.edge].map((entry) => entry.kind).sort();
  const catalogKinds = [...resourceKinds, ...referenceKinds].sort();
  if (
    new Set(resourceKinds).size !== resourceKinds.length
    || new Set(referenceKinds).size !== referenceKinds.length
    || JSON.stringify(catalogKinds) !== JSON.stringify(allKinds)
  ) fail("potential resource and reference-only handle partition drift");
  if (JSON.stringify([...referenceKinds].sort()) !== JSON.stringify(["credentialKey", "credentialLineage"])) {
    fail("only credential lineage/key handles may be reference-only");
  }
  const brokerKinds = new Set(handles.broker.map((entry) => entry.kind));
  for (const resource of catalog.resources) {
    if ((resource.server === "broker") !== brokerKinds.has(resource.handleKind)) {
      fail(`potential resource server/handle realm mismatch: ${resource.handleKind}`);
    }
    if (resource.handleKind === "localBinding" && resource.server !== "edge-control") {
      fail("localBinding must be served by edge-control");
    }
    if (resource.handleKind === "localProvider" && resource.server !== "provider-ingress") {
      fail("localProvider must be served by provider-ingress");
    }
    const expectedCache = resource.handleKind === "reasonCodes"
      ? { cacheScope: "public", ttlMs: 3_600_000 }
      : { cacheScope: "private", ttlMs: 0 };
    if (
      resource.cache.cacheScope !== expectedCache.cacheScope
      || resource.cache.ttlMs !== expectedCache.ttlMs
    ) fail(`potential resource cache drift: ${resource.handleKind}`);
  }

  const tools = new Map(catalog.tools.map((entry) => [entry.name, entry]));
  if (tools.size !== catalog.tools.length) fail("potential tool names must be unique");
  if (catalog.tools.filter((entry) => entry.server === "broker").length !== 27) {
    fail("potential broker tool count drift");
  }
  if (catalog.tools.filter((entry) => entry.server !== "broker").length !== 10) {
    fail("potential local tool count drift");
  }
  for (const entry of authenticationHeaders.responseHeaders) {
    for (const method of [entry.method, ...(entry.alternateMethods ?? [])]) {
      const tool = tools.get(method);
      if (!tool || tool.server !== entry.server) {
        fail(`authentication header route is absent from potential catalog: ${method}`);
      }
    }
  }
  for (const entry of authenticationHeaders.secretFreeResults) {
    for (const method of [entry.method, ...(entry.alternateMethods ?? [])]) {
      const tool = tools.get(method);
      if (!tool || tool.server !== entry.server) {
        fail(`secret-free result route is absent from potential catalog: ${method}`);
      }
    }
  }
  for (const entry of authenticationHeaders.requestOnlyHeaders) {
    if (!tools.has(entry.method)) {
      fail(`request-only authentication reference is absent from potential catalog: ${entry.method}`);
    }
  }
}

function templatesOverlap(left, right) {
  const leftSegments = left.split("/");
  const rightSegments = right.split("/");
  if (leftSegments.length !== rightSegments.length) return false;
  return leftSegments.every((segment, index) => {
    const other = rightSegments[index];
    return segment === other || segment.startsWith("{") || other.startsWith("{");
  });
}

async function verifyVendoredArtifact(name, provenance) {
  if (
    !provenance
    || !/^[0-9a-f]{40}$/.test(provenance.gitBlob)
    || !/^[0-9a-f]{64}$/.test(provenance.sha256)
    || typeof provenance.vendoredPath !== "string"
  ) fail(`${name} provenance is incomplete`);
  const bytes = await readFile(await resolveVendoredPath(provenance.vendoredPath));
  const digest = createHash("sha256").update(bytes).digest("hex");
  if (digest !== provenance.sha256) fail(`${name} sha256 drift`);
  const gitBlob = createHash("sha1")
    .update(`blob ${bytes.byteLength}\0`)
    .update(bytes)
    .digest("hex");
  if (gitBlob !== provenance.gitBlob) fail(`${name} git blob drift`);
  if (provenance.size !== undefined && bytes.byteLength !== provenance.size) {
    fail(`${name} size drift`);
  }
  return bytes;
}

async function verifyFixtureCorpus(corpus, fixtureManifest) {
  const expected = {
    repository: "modelcontextprotocol/modelcontextprotocol",
    commit: "71e306956a4959c9655e5036be215d41986596e6",
    tree: "1a9a888cd20b7d1a898121992cf33d119f5f80e5",
    path: "schema/draft/examples",
    fileCount: 128,
    hashAlgorithm: "sha256-v1(relative-path NUL bytes NUL)",
    sha256: "bae6de868193aed37ce379fbb1de2455599b0eede87cec1d7b44ba5c29e49ae5",
  };
  for (const [field, expectedValue] of Object.entries(expected)) {
    if (corpus?.[field] !== expectedValue) fail(`stable core corpus ${field} drift`);
  }
  if (
    fixtureManifest.source?.repo !== corpus.repository
    || fixtureManifest.source?.commit !== corpus.commit
    || fixtureManifest.source?.path !== corpus.path
  ) fail("stable core corpus source does not match fixture manifest");

  const corpusRoot = await resolveVendoredPath(corpus.vendoredPath);
  const files = (await walkFiles(corpusRoot)).sort();
  const actualPaths = files.map((file) => relative(corpusRoot, file).split(sep).join("/"));
  const expectedPaths = Object.entries(fixtureManifest.directories)
    .flatMap(([directory, names]) => names.map((name) => `${directory}/${name}`))
    .sort();
  if (
    files.length !== corpus.fileCount
    || new Set(actualPaths).size !== files.length
    || JSON.stringify(actualPaths) !== JSON.stringify(expectedPaths)
  ) fail("stable core corpus file set drift");

  const treeObjectId = await gitTreeObjectId(corpusRoot);
  if (treeObjectId !== corpus.tree) {
    fail(`stable core corpus git tree drift: expected ${corpus.tree}, got ${treeObjectId}`);
  }

  const digest = createHash("sha256");
  for (let index = 0; index < files.length; index += 1) {
    const bytes = await readFile(files[index]);
    JSON.parse(bytes.toString("utf8"));
    digest.update(actualPaths[index]);
    digest.update("\0");
    digest.update(bytes);
    digest.update("\0");
  }
  if (digest.digest("hex") !== corpus.sha256) fail("stable core corpus sha256 drift");
}

async function gitTreeObjectId(directory) {
  const entries = await Promise.all((await readdir(directory, { withFileTypes: true })).map(async (entry) => {
    const path = resolve(directory, entry.name);
    if (entry.isDirectory()) {
      return { name: entry.name, mode: "40000", objectId: await gitTreeObjectId(path), directory: true };
    }
    if (entry.isFile()) {
      const metadata = await stat(path);
      if ((metadata.mode & 0o111) !== 0) {
        fail(`executable fixture corpus entry cannot match pinned 100644 tree mode: ${path}`);
      }
      const bytes = await readFile(path);
      const objectId = createHash("sha1")
        .update(`blob ${bytes.byteLength}\0`)
        .update(bytes)
        .digest("hex");
      return { name: entry.name, mode: "100644", objectId, directory: false };
    }
    fail(`unsupported fixture corpus entry: ${path}`);
  }));
  entries.sort((left, right) => Buffer.compare(
    Buffer.from(`${left.name}${left.directory ? "/" : ""}`, "utf8"),
    Buffer.from(`${right.name}${right.directory ? "/" : ""}`, "utf8"),
  ));
  const body = Buffer.concat(entries.flatMap((entry) => [
    Buffer.from(`${entry.mode} ${entry.name}\0`, "utf8"),
    Buffer.from(entry.objectId, "hex"),
  ]));
  return createHash("sha1")
    .update(`tree ${body.byteLength}\0`)
    .update(body)
    .digest("hex");
}

async function resolveVendoredPath(vendoredPath) {
  if (typeof vendoredPath !== "string" || !vendoredPath.startsWith("schemas/upstream/")) {
    fail(`invalid vendored path: ${String(vendoredPath)}`);
  }
  const lexicalPath = resolve(root, vendoredPath);
  const lexicalRelative = relative(upstreamRoot, lexicalPath);
  if (lexicalRelative === ".." || lexicalRelative.startsWith(`..${sep}`)) {
    fail(`vendored path escapes repository: ${vendoredPath}`);
  }
  let resolvedPath;
  try {
    resolvedPath = await realpath(lexicalPath);
  } catch {
    fail(`vendored path is missing or unreadable: ${vendoredPath}`);
  }
  const realRelative = relative(realUpstreamRoot, resolvedPath);
  if (realRelative === ".." || realRelative.startsWith(`..${sep}`)) {
    fail(`vendored path resolves outside repository: ${vendoredPath}`);
  }
  return resolvedPath;
}

async function walkFiles(directory) {
  const files = [];
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const path = resolve(directory, entry.name);
    if (entry.isDirectory()) files.push(...await walkFiles(path));
    else if (entry.isFile()) files.push(path);
    else fail(`unsupported fixture corpus entry: ${path}`);
  }
  return files;
}

function escapeRegex(value) {
  return value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

function fail(message) {
  process.stderr.write(`${message}\n`);
  process.exit(1);
}
